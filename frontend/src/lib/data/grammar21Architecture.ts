// Helper to extract seeded questions for a lesson
function getSeedQuestionsForLesson(topicId: string, lessonId: string): BankQuestion[] {
  return INITIAL_QUESTION_BANK.filter(
    (q) => q.topicId === topicId && (q.lessonId === lessonId || !q.lessonId)
  );
}

